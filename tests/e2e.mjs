import { strict as assert } from 'node:assert';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const baseURL=process.env.AKASHEET_TEST_URL||'http://localhost:5173/';
const artifacts=process.env.AKASHEET_QA_DIR||fileURLToPath(new URL('../test-results',import.meta.url));
await mkdir(artifacts,{recursive:true});
const executablePath=process.env.CHROMIUM_PATH||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined);
const browser=await chromium.launch({headless:true,executablePath,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
const page=await context.newPage();
const errors=[]; const requestFailures=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('requestfailed',r=>requestFailures.push({url:r.url(),failure:r.failure()?.errorText}));
const canvas=()=>page.locator('.canvas-container canvas');
const waitCanvas=async()=>{await page.locator('.canvas-container canvas:not(.canvas-loading)').waitFor({state:'visible'});await page.waitForFunction(()=>{const c=document.querySelector('.canvas-container canvas');return c&&c.width>0&&c.height>0;});};
const pixels=async()=>canvas().evaluate(c=>{const d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let red=0,black=0;for(let i=0;i<d.length;i+=4){if(d[i]>d[i+1]+40&&d[i]>d[i+2]+30&&d[i+1]<140)red++;if(d[i]<60&&d[i+1]<60&&d[i+2]<60)black++;}return{red,black,width:c.width,height:c.height};});
try{
  await page.goto(baseURL);
  await page.getByRole('button',{name:'サンプルPDFで試す'}).waitFor();
  await page.screenshot({path:`${artifacts}/desktop-library.png`,fullPage:true});
  await page.getByRole('button',{name:'サンプルPDFで試す'}).click();
  await waitCanvas();
  assert.equal(await page.getByRole('switch').getAttribute('aria-checked'),'true');
  const hidden=await pixels();
  await page.getByRole('switch').click();
  const visible=await pixels();
  assert.ok(visible.red>1000,`sample should have red answer pixels: ${JSON.stringify(visible)}`);
  assert.ok(hidden.red<visible.red*0.02,`sheet should erase red answer pixels: ${JSON.stringify({hidden,visible})}`);
  assert.ok(hidden.black>visible.black*0.75,`black questions should remain: ${JSON.stringify({hidden,visible})}`);
  await page.getByRole('switch').click();
  const peek=page.getByRole('button',{name:'押して答えを見る'});
  const box=await peek.boundingBox();assert.ok(box);await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  assert.ok((await pixels()).red>1000,'hold reveals answers');await page.mouse.up();
  assert.ok((await pixels()).red<visible.red*0.02,'release hides answers');
  await page.getByRole('button',{name:'次のページ'}).click();await waitCanvas();
  assert.equal(await page.getByRole('textbox',{name:'ページ番号'}).inputValue(),'2');
  assert.equal(await page.getByRole('switch').getAttribute('aria-checked'),'true','new page defaults hidden');
  await page.getByRole('button',{name:'しおりを付ける',exact:true}).click();
  await page.getByRole('button',{name:'しおりを外す',exact:true}).waitFor();
  await page.getByRole('button',{name:'調整',exact:true}).click();
  await page.getByLabel('赤字を隠す感度').fill('80');
  await page.getByRole('button',{name:'調整を閉じる'}).click();
  await page.waitForTimeout(400);
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'PDFを保存',exact:true}).click();const download=await downloadPromise;assert.ok(download.suggestedFilename().endsWith('.pdf'));assert.equal(await download.failure(),null);
  await page.screenshot({path:`${artifacts}/desktop-viewer.png`,fullPage:true});
  await page.reload();
  const card=page.getByRole('button',{name:'サンプル｜理科と英語の暗記シートを開く',exact:true});await card.waitFor();await card.click();await waitCanvas();
  assert.equal(await page.getByRole('textbox',{name:'ページ番号'}).inputValue(),'2','page persists after reload');
  assert.equal(await page.getByRole('button',{name:'しおりを外す',exact:true}).getAttribute('aria-pressed'),'true','bookmark persists');
  await page.getByRole('button',{name:'調整',exact:true}).click();assert.equal(await page.getByLabel('赤字を隠す感度').inputValue(),'80','sensitivity persists');await page.getByRole('button',{name:'調整を閉じる'}).click();
  await page.getByRole('button',{name:'ライブラリに戻る',exact:true}).click();
  await page.getByLabel('PDFファイルを選択').setInputFiles(fileURLToPath(new URL('../public/sample.pdf',import.meta.url)));
  await waitCanvas();assert.equal(await page.getByRole('heading',{name:'sample',exact:true}).count(),1,'raw PDF import opens viewer');
  await page.getByRole('button',{name:'ライブラリに戻る',exact:true}).click();
  await page.getByLabel('PDFファイルを選択').setInputFiles({name:'broken.pdf',mimeType:'application/pdf',buffer:Buffer.from('invalid file')});
  await page.getByRole('alert').waitFor();assert.match(await page.getByRole('alert').innerText(),/PDF形式/);
  await page.getByRole('button',{name:'通知を閉じる'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.thumbnail canvas')).every(c=>c.width>300));
  await page.screenshot({path:`${artifacts}/mobile-library.png`,fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile library has no horizontal overflow');
  await page.getByRole('button',{name:'サンプル｜理科と英語の暗記シートを開く',exact:true}).click();await waitCanvas();
  assert.ok(await page.getByRole('switch').isVisible(),'mobile red-sheet switch visible');assert.ok(await page.getByRole('button',{name:'次のページ'}).isVisible(),'mobile navigation visible');
  await page.screenshot({path:`${artifacts}/mobile-viewer.png`,fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'mobile viewer has no horizontal overflow');
  assert.deepEqual(errors,[],'no JavaScript errors');
  console.log(JSON.stringify({status:'passed',checks:['sample rendering','red pixels hidden','black questions retained','hold to peek','page navigation','bookmark persistence','page persistence','sensitivity persistence','PDF download','raw PDF import','invalid PDF error','desktop/mobile layout'],pixels:{hidden,visible},requestFailures},null,2));
}finally{await browser.close();}
